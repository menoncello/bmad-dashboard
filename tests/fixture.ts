// the status tool hands back JSON: the summary by default, else the section asked for
export async function status($: any, section?: string) {
  const r = await $.tool.call({ tool: 'mcp__bmad-dashboard__status', ...(section ? { section } : {}) })
  return JSON.parse(r.result as string)
}

// polls until `check` holds: for work a test starts without awaiting it
export async function until(check: () => boolean | Promise<boolean>, what = 'condition', ms = 3000): Promise<void> {
  const end = Date.now() + ms
  while (!(await check())) {
    if (Date.now() > end) throw new Error(`timed out waiting for ${what}`)
    await new Promise(r => setTimeout(r, 5))
  }
}

