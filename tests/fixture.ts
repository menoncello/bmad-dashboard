export function children(dir: string, files = FILES) {
  const out = new Map<string, 'file' | 'dir'>()
  for (const f of Object.keys(files)) {
    if (!f.startsWith(dir + '/')) continue
    const rest = f.slice(dir.length + 1).split('/')
    out.set(rest[0]!, rest.length > 1 ? 'dir' : 'file')
  }
  return out
}

// The collectors cache parsed files by path, mtime and size. A mtime derived from the
// content keeps a test from reading a stale parse left by another test's file at the same path.
const mtimeOf = (text: string) => {
  let h = 1
  for (let i = 0; i < text.length; i++) h = (h * 31 + text.charCodeAt(i)) % 1_000_003
  return h
}

// What `ps -p <pid> -o command=` prints for a pid: a command line, or undefined
// for no such process (exit 1, nothing printed).
export type PsAnswer = (pid: string) => string | undefined
const ENGINE = 'python -m bmad_loop.cli run\n'

export type ProcResult = { exitCode: number; stdout: string; stderr: string }

// Extras for a test: `calls` collects the argv of every process.run, `run` answers a
// command itself (return undefined to leave it to the defaults below; it may be async, to
// hold a command), `panes` says which panes are open (none by default).
export type FakeOptions = {
  calls?: string[][]
  run?: (argv: readonly string[]) => ProcResult | undefined | Promise<ProcResult | undefined>
  panes?: () => string[]
  // what the store holds at the start, and every write to it
  store?: Record<string, unknown>
  writes?: { key: string; value: unknown }[]
  // the ids ui.open was asked for, and the specs tool.register was given
  opened?: string[]
  tools?: { name: string; description?: string; inputSchema?: unknown }[]
}

// operation hooks answer `{ value }`; `ps` varies the process table per test.
// Every call starts the collectors' module-level caches over, so tests cannot leak into each other.
export function fakeProject(on: any, files = FILES, cwd = ROOT, ps: PsAnswer = () => ENGINE, extra: FakeOptions = {}) {
  resetCaches()
  // the plugin's store, in memory; the returned map is the store itself
  const store = new Map<string, unknown>(Object.entries(extra.store ?? {}))
  on('store.get', (_$: unknown, e: { key: string }) => ({ value: store.get(e.key) }))
  on('store.set', (_$: unknown, e: { key: string; value: unknown }) => {
    extra.writes?.push({ key: e.key, value: e.value })
    store.set(e.key, e.value)
    return { value: undefined }
  })
  on('store.delete', (_$: unknown, e: { key: string }) => ({ value: void store.delete(e.key) }))
  on('store.keys', () => ({ value: [...store.keys()] }))
  on('ui.status', () => ({ value: undefined }))
  on('ui.open', (_$: unknown, e: { id: string }) => {
    extra.opened?.push(e.id)
    return { value: { isPlaced: true } }
  })
  on('ui.panes', () => ({ value: (extra.panes?.() ?? []).map(id => ({ id })) as never }))
  // what session.start registers, and the engine's own answer to it
  on('command.register', () => ({ value: { command: 'bmad-dashboard' } }))
  on('tool.register', (_$: unknown, e: { name: string }) => {
    extra.tools?.push(e as never)
    return { value: { tool: e.name } }
  })
  on('session.start', (_$: unknown, e: { cwd: string }) => ({ cwd: e.cwd }))
  const isDir = (p: string) => children(p, files).size > 0
  on('session.cwd', () => ({ value: cwd }))
  on('fs.exists', (_$: unknown, e: { path: string }) => ({ value: e.path in files || isDir(e.path) }))
  on('fs.read', (_$: unknown, e: { path: string }) => {
    if (!(e.path in files)) throw new Error('ENOENT')
    return { value: files[e.path] }
  })
  on('fs.stat', (_$: unknown, e: { path: string }) => {
    if (e.path in files) return { value: { kind: 'file', size: files[e.path]!.length, mtimeMs: mtimeOf(files[e.path]!), isLink: false } }
    if (isDir(e.path)) return { value: { kind: 'dir', size: 0, mtimeMs: 0, isLink: false } }
    throw new Error('ENOENT')
  })
  on('fs.list', (_$: unknown, e: { path: string }) => ({
    value: [...children(e.path, files)].map(([name, kind]) => ({ name, kind, size: kind === 'file' ? files[`${e.path}/${name}`]!.length : 0, mtimeMs: kind === 'file' ? mtimeOf(files[`${e.path}/${name}`]!) : 0, isLink: false })),
  }))
  // the virtual tickets.py holds the JSON it would print, so reading it stands in for running it;
  // python3 and `uv run` both run it
  on('process.run', async (_$: unknown, e: { argv: readonly string[] }) => {
    extra.calls?.push([...e.argv])
    const custom = await extra.run?.(e.argv)
    if (custom) return { value: custom }
    const script = `${cwd}/_bmad/method/scripts/tickets.py`
    const rest = e.argv[0] === 'python3' ? e.argv.slice(1) : e.argv[0] === 'uv' && e.argv[1] === 'run' ? e.argv.slice(2) : undefined
    if (rest && rest.join(' ') === `${script} --project-root ${cwd} status` && script in files) return { value: { exitCode: 0, stdout: files[script], stderr: '' } }
    if (e.argv[0] === 'ps') {
      const out = ps(e.argv[2] ?? '')
      return { value: { exitCode: out === undefined ? 1 : 0, stdout: out ?? '', stderr: '' } }
    }
    return { value: { exitCode: 1, stdout: '', stderr: '' } }
  })
  return store
}

