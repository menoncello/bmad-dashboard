import { describe, expect, test } from 'claude-code/testing'

import { frontmatter, parseCsv, parseToml, parseYaml } from '../hooks/parse'

describe('parseYaml scalars', () => {
  test('numbers convert only when they round-trip', () => {
    expect(parseYaml('a: 2\nb: -3\nc: 3.5\nd: 6.10\ne: 1.0\nf: 007\ng: 1.20')).toEqual({
      a: 2,
      b: -3,
      c: 3.5,
      d: '6.10',
      e: '1.0',
      f: '007',
      g: '1.20',
    })
  })

  test('booleans and null', () => {
    expect(parseYaml('a: true\nb: false\nc: null\nd: ~\ne:')).toEqual({ a: true, b: false, c: null, d: null, e: null })
  })

  test('quoted strings keep colons and hashes', () => {
    expect(parseYaml('a: "x: y # z"\nb: \'it\'\'s # ok\'\nc: "plain"')).toEqual({
      a: 'x: y # z',
      b: "it's # ok",
      c: 'plain',
    })
  })

  test('trailing comments are stripped, urls stay strings', () => {
    expect(parseYaml('key: value # comment\nrepo: https://github.com/a/b\nanchor: http://x/#frag')).toEqual({
      key: 'value',
      repo: 'https://github.com/a/b',
      anchor: 'http://x/#frag',
    })
  })
})

describe('parseYaml structure', () => {
  test('nested maps', () => {
    expect(parseYaml('a:\n  b:\n    c: 1\n  d: 2\ne: 3')).toEqual({ a: { b: { c: 1 }, d: 2 }, e: 3 })
  })

  test('list of maps and scalar lists', () => {
    expect(parseYaml('items:\n  - id: 1\n    name: one\n  - id: 2\n    name: two\ntags:\n  - a\n  - b')).toEqual({
      items: [
        { id: 1, name: 'one' },
        { id: 2, name: 'two' },
      ],
      tags: ['a', 'b'],
    })
  })

  test('list at the same indent as its key', () => {
    expect(parseYaml('a:\n- x\n- y\nb: 1')).toEqual({ a: ['x', 'y'], b: 1 })
  })

  test('single-line flow collections', () => {
    expect(parseYaml('a: [x, "y, z", 3]\nb: {k: v, n: 1}')).toEqual({ a: ['x', 'y, z', 3], b: { k: 'v', n: 1 } })
  })

  test('sprint-status shape', () => {
    const src = `# generated by sprint planning
generated: 10-16-2026 09:11
project: fulcro
development_status:
  epic-1: done
  1-1-walking-skeleton: done
  1-2a-second-story: in-progress # note
  epic-1-retrospective: optional
`
    expect(parseYaml(src)).toEqual({
      generated: '10-16-2026 09:11',
      project: 'fulcro',
      development_status: {
        'epic-1': 'done',
        '1-1-walking-skeleton': 'done',
        '1-2a-second-story': 'in-progress',
        'epic-1-retrospective': 'optional',
      },
    })
  })

  test('document markers and empty input', () => {
    expect(parseYaml('---\na: 1\n')).toEqual({ a: 1 })
    expect(parseYaml('')).toBe(null)
    expect(parseYaml('# only a comment\n')).toBe(null)
  })
})

describe('parseYaml multi-line flow collections', () => {
  test('flow list on the line after the key', () => {
    expect(parseYaml('steps:\n  [a,\n   b]\nnext: 1')).toEqual({ steps: ['a', 'b'], next: 1 })
  })

  test('flow list opened on the key line', () => {
    expect(parseYaml('steps: [a,\n  b]\nnext: 1')).toEqual({ steps: ['a', 'b'], next: 1 })
  })

  test('nested flow with comments and blank lines inside', () => {
    expect(parseYaml('o: {a: 1,\n\n  # note\n  b: [x,\n y]}\nn: 2')).toEqual({ o: { a: 1, b: ['x', 'y'] }, n: 2 })
  })

  test('flow list as a list item', () => {
    expect(parseYaml('- [a,\n  b]\n- c')).toEqual([['a', 'b'], 'c'])
  })
})

describe('parseYaml block scalars', () => {
  test('headers with chomping and indentation indicators', () => {
    expect(parseYaml('a: |+\n  x\nb: >2\n  y')).toEqual({ a: 'x\n', b: 'y' })
    expect(parseYaml('a: |-\n  x\nb: |2-\n  y\nc: >+2\n  z\nd: 1')).toEqual({ a: 'x', b: 'y', c: 'z\n', d: 1 })
  })

  test('blank lines and # lines inside the block are content', () => {
    expect(parseYaml('desc: |\n  line one\n\n  # heading\n  line two\nk: v')).toEqual({
      desc: 'line one\n\n# heading\nline two',
      k: 'v',
    })
  })

  test('a hash inside block text is not a comment', () => {
    expect(parseYaml('d: |\n  keep # this\nk: v')).toEqual({ d: 'keep # this', k: 'v' })
  })

  test('deeper indentation is kept relative to the block', () => {
    expect(parseYaml('d: |\n  a\n    b\n  c\nk: v')).toEqual({ d: 'a\n  b\nc', k: 'v' })
  })

  test('folded blocks join with a space, blank line becomes a newline', () => {
    expect(parseYaml('d: >\n  a\n  b\n\n  c\nk: v')).toEqual({ d: 'a b\nc', k: 'v' })
    expect(parseYaml('d: >-\n  a\n  b\nk: v')).toEqual({ d: 'a b', k: 'v' })
  })

  test('clip and strip give no trailing newline, keep may', () => {
    expect(parseYaml('a: |\n  x\n\nb: |-\n  y\n\nc: |+\n  z\n\nd: 1')).toEqual({ a: 'x', b: 'y', c: 'z\n\n', d: 1 })
  })

  test('block scalar inside a list of maps', () => {
    expect(parseYaml('items:\n  - id: 1\n    desc: |\n      hello\n\n      world\n    n: 2\n  - id: 2')).toEqual({
      items: [{ id: 1, desc: 'hello\n\nworld', n: 2 }, { id: 2 }],
    })
  })

  test('block scalar header followed by a trailing comment', () => {
    expect(parseYaml('a: | # why\n  x\nb: 1')).toEqual({ a: 'x', b: 1 })
  })
})

describe('frontmatter', () => {
  test('LF and CRLF', () => {
    const lf = frontmatter('---\ntitle: Hi\nversion: 6.10\n---\nbody\n')
    expect(lf.fm).toEqual({ title: 'Hi', version: '6.10' })
    expect(lf.body).toBe('body\n')
    const crlf = frontmatter('---\r\ntitle: Hi\r\ntags:\r\n  - a\r\n---\r\nbody\r\n')
    expect(crlf.fm).toEqual({ title: 'Hi', tags: ['a'] })
    expect(crlf.body).toBe('body\r\n')
  })

  test('no frontmatter', () => {
    expect(frontmatter('# Title\n')).toEqual({ fm: {}, body: '# Title\n' })
  })

  test('block scalar with a heading line inside frontmatter', () => {
    expect(frontmatter('---\ndesc: |\n  a\n\n  # b\n---\nx').fm).toEqual({ desc: 'a\n\n# b' })
  })
})

describe('parseToml', () => {
  test('inline tables and arrays', () => {
    expect(parseToml('a = { x = 1, y = "two" }\nb = [1, 2, 3]\nc = true')).toEqual({
      a: { x: 1, y: 'two' },
      b: [1, 2, 3],
      c: true,
    })
  })

  test('[[array]] tables and nested tables', () => {
    const src = '[[agent]]\nname = "a"\n\n[[agent]]\nname = "b"\n\n[core]\nlang = "en"\n[core.sub]\nk = 1'
    expect(parseToml(src)).toEqual({
      agent: [{ name: 'a' }, { name: 'b' }],
      core: { lang: 'en', sub: { k: 1 } },
    })
  })

  test('multi-line arrays with comments', () => {
    expect(parseToml('list = [\n  "a", # first\n  "b",\n]\nafter = 1')).toEqual({ list: ['a', 'b'], after: 1 })
  })

  test('triple-quoted strings', () => {
    expect(parseToml('s = """\nline one\nline # two\n"""\nn = 1')).toEqual({ s: '\nline one\nline # two\n', n: 1 })
  })

  test('quoted dotted keys', () => {
    expect(parseToml('"c.d".e = 2\n[tool."a.b"]\nx = 1\n"k.l".m = 3')).toEqual({
      'c.d': { e: 2 },
      tool: { 'a.b': { x: 1, 'k.l': { m: 3 } } },
    })
  })
})

describe('parseCsv', () => {
  test('quoted cells with commas, quotes and newlines', () => {
    expect(parseCsv('name,desc\na,"x, y"\nb,"line1\nline2"\nc,"say ""hi"""\n')).toEqual([
      { name: 'a', desc: 'x, y' },
      { name: 'b', desc: 'line1\nline2' },
      { name: 'c', desc: 'say "hi"' },
    ])
  })

  test('CRLF rows and missing cells', () => {
    expect(parseCsv('a,b\r\n1,2\r\n3\r\n')).toEqual([
      { a: '1', b: '2' },
      { a: '3', b: '' },
    ])
  })

  test('empty input', () => {
    expect(parseCsv('')).toEqual([])
  })
})
