function children(dir: string) {
  const out = new Map<string, 'file' | 'dir'>()
  for (const f of Object.keys(FILES)) {
    if (!f.startsWith(dir + '/')) continue
    const rest = f.slice(dir.length + 1).split('/')
    out.set(rest[0]!, rest.length > 1 ? 'dir' : 'file')
  }
  return out
}

// operation hooks answer `{ value }`
function fakeProject(on: any) {
  mock.store(on)
  on('ui.status', () => ({ value: undefined }))
  on('ui.open', () => ({ value: { isPlaced: true } }))
  const isDir = (p: string) => children(p).size > 0
  on('session.cwd', () => ({ value: ROOT }))
  on('fs.exists', (_$: unknown, e: { path: string }) => ({ value: e.path in FILES || isDir(e.path) }))
  on('fs.read', (_$: unknown, e: { path: string }) => {
    if (!(e.path in FILES)) throw new Error('ENOENT')
    return { value: FILES[e.path] }
  })
  on('fs.stat', (_$: unknown, e: { path: string }) => {
    if (e.path in FILES) return { value: { kind: 'file', size: FILES[e.path]!.length, mtimeMs: 1, isLink: false } }
    if (isDir(e.path)) return { value: { kind: 'dir', size: 0, mtimeMs: 0, isLink: false } }
    throw new Error('ENOENT')
  })
  on('fs.list', (_$: unknown, e: { path: string }) => ({
    value: [...children(e.path)].map(([name, kind]) => ({ name, kind, size: kind === 'file' ? FILES[`${e.path}/${name}`]!.length : 0, mtimeMs: 1, isLink: false })),
  }))
  on('process.run', (_$: unknown, e: { argv: readonly string[] }) => ({
    value: e.argv[0] === 'ps' ? { exitCode: 0, stdout: 'python -m bmad_loop.cli run\n', stderr: '' } : { exitCode: 1, stdout: '', stderr: '' },
  }))
}

describe('pane over a project', () => {
  for (const surface of ['terminal', 'desktop'] as const) {
    test(`reads the project and every tab draws on ${surface}`, async ($, on) => {
      fakeProject(on)
      await $.command.run({ command: 'bmad-dashboard', args: '' } as never)
      const ui = await $.ui.mount({
        plugin: 'bmad-dashboard',
        surface,
        component: 'Pane',
        requestId: 'bmad',
        props: { title: 'BMAD', isFocused: true, bodyColumns: 90, placement: 'dock' } as never,
      })
      expect(await ui.find({ type: 'Text', text: /demo/ })).toBeDefined()
      for (const id of ['sprint', 'loop', 'planning', 'quality', 'debt', 'modules', 'projects', 'overview']) {
        await ui.press({ key: `tab-${id}` })
        expect(await ui.find({ type: 'Text' })).toBeDefined()
      }
      await ui.press({ key: 'tab-loop' })
      expect(await ui.find({ type: 'Text', text: /4380/ })).toBeDefined()
      expect(await ui.find({ type: 'Text', text: /dev-running/ })).toBeDefined()
      await ui.press({ key: 'tab-quality' })
      expect(await ui.find({ type: 'Text', text: /FAIL/ })).toBeDefined()
      await ui.press({ key: 'tab-sprint' })
      expect(await ui.find({ type: 'Text', text: /Second/ })).toBeDefined()
      await ui.unmount()
    })
  }
})
